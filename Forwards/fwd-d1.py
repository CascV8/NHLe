"""
NHLe Forward D+1 Model (age ~19)
================================
Predicts NHL outcomes from 1 season after the draft year.

Outputs two probabilities on a single bar (Iacobelli-style):
  - P(NHL player) : reaches 200 NHL games
  - P(Star)       : peak GAR (mean of best 3 seasons) in the top 15% of NHL forwards

The World Juniors (WJC-20) are their own fitted term, not pooled into
pts/82: making the team and scoring there move the odds on top of the
league season (NHLER_WJC / STAR_WJC), so a big tournament counts for more
than its 7 games would.

Generated by training/fit.py --write from training/model_template.py.in: edit the
template, not this file. Coefficients are fit on the 2006-2018 NHL draft
classes, league factors are the network NHLe factors (training/NETWORK.md),
and training/REPORT.md has the sample size, star threshold and accuracy.

Usage:
    python fwd-d1.py                  # interactive
    python fwd-d1.py --pts82 <value>  # pre-calculated pts/82 (no World Juniors)

League names have no spaces (use dashes). Type 'leagues' at any prompt to list all.
"""

import math
import sys

# ── Model coefficients ── fit by training/fit.py, see training/REPORT.md ─────
# log-odds = INTERCEPT + COEF * pts/82, plus for each World Juniors played:
#            PLAYED + PER_PTS82 * (that tournament's NHLe pts/82)
NHLER_INTERCEPT = -2.730459
NHLER_COEF      =  0.132380
NHLER_WJC       = {"wjc-20": (0.870004, -0.000792)}

STAR_INTERCEPT  = -6.000706
STAR_COEF       =  0.132210
STAR_WJC        = {"wjc-20": (0.704162, 0.031540)}
# ─────────────────────────────────────────────────────────────────────────────

LEAGUE_FACTORS = {
    "nhl":           1.000000,
    "khl":           0.636133,
    "shl":           0.514399,
    "nl":            0.465607,
    "czechia":       0.435006,
    "del":           0.392552,
    "ahl":           0.379607,
    "liiga":         0.377087,
    "vhl":           0.272342,
    "wjc-20":        0.270304,
    "allsvenskan":   0.218316,
    "ncaa":          0.210347,
    "slovakia":      0.199571,
    "ohl":           0.147264,
    "czechia2":      0.144836,
    "mestis":        0.136663,
    "echl":          0.134079,
    "whl":           0.131703,
    "qmjhl":         0.123518,
    "ushl":          0.122643,
    "sl":            0.121523,
    "del2":          0.118766,
    "mhl":           0.118318,
    "wjc-18":        0.115349,
    "u20-sm-sarja":  0.083636,
    "hockeyettan":   0.077375,
    "bchl":          0.073694,
    "u20-nationell": 0.071012,
    "czechia-u20":   0.060447,
    "cchl":          0.049304,
    "ajhl":          0.049274,
    "ojhl":          0.042749,
    "sjhl":          0.039817,
    "u18-sm-sarja":  0.032699,
    "mjahl":         0.032597,
    "mjhl":          0.031926,
    "u18-nationell": 0.027494,
    "kijhl":         0.013208,
}
TOURNAMENTS = ('wjc-20',)
KNOWN_OUTCOMES = False


def parse_league(raw):
    key = raw.strip().lower()
    if key in LEAGUE_FACTORS and key not in TOURNAMENTS:
        return key, LEAGUE_FACTORS[key]
    try:
        factor = float(key)
    except ValueError:
        raise ValueError(f"Unknown league '{raw}'. Type 'leagues' to list.") from None
    if not (0 < factor <= 1):
        raise ValueError(f"Custom NHLe factor must be between 0 and 1, got '{raw}'.")
    return key, factor


def parse_num(raw):
    """float() that rejects nan, inf and negative values."""
    val = float(raw)
    if not math.isfinite(val) or val < 0:
        raise ValueError(f"expected a non-negative number, got '{raw}'")
    return val


def wjc_log_odds(terms, wjc):
    """The World Juniors term: ``wjc`` maps a tournament to its NHLe pts/82."""
    return sum(terms[t][0] + terms[t][1] * x for t, x in (wjc or {}).items() if t in terms)


def p_nhler(pts82, wjc=None):
    lo = NHLER_INTERCEPT + NHLER_COEF * pts82 + wjc_log_odds(NHLER_WJC, wjc)
    return 1.0 / (1.0 + math.exp(-lo))


def p_star(pts82, wjc=None):
    lo = STAR_INTERCEPT + STAR_COEF * pts82 + wjc_log_odds(STAR_WJC, wjc)
    return min(1.0 / (1.0 + math.exp(-lo)), p_nhler(pts82, wjc))


def compute_pts82(stints):
    total_nhle_pts = sum(s["pts"] * s["factor"] for s in stints)
    total_gp       = sum(s["gp"] for s in stints)
    return (total_nhle_pts / total_gp) * 82 if total_gp > 0 else 0.0


def render_bar(p_nhl, p_str, width=40):
    n_star  = round(p_str * width)
    n_nhler = max(round(p_nhl * width), n_star)
    n_empty = width - n_nhler
    return "[" + "★" * n_star + "█" * (n_nhler - n_star) + "░" * n_empty + "]"


def show_result(pts82, stints=None, wjc_stints=(), known_nhler=False, known_star=False):
    wjc = {s["league_key"]: s["pts"] * s["factor"] / s["gp"] * 82 for s in wjc_stints}
    pn = 1.0 if (known_nhler or known_star) else p_nhler(pts82, wjc)
    ps = 1.0 if known_star else p_star(pts82, wjc)

    print()
    print("  " + "═" * 52)
    if known_star:
        print("  ⚡ Known outcome: player has already reached star threshold.")
    elif known_nhler:
        print("  ⚡ Known outcome: player has already reached 200 GP.")

    if stints:
        for s in stints:
            tag = {"reg": "Reg    ", "po": "Playoff"}[s["kind"]]
            print(f"  {tag}  {s['league_key'].upper():<14}"
                  f"{s['pts']:>5.1f}pts/{s['gp']:>4.1f}gp "
                  f"({s['pts'] / s['gp']:.3f} PPG) × {s['factor']:.4f}")
        total_nhle = sum(s["pts"] * s["factor"] for s in stints)
        total_gp   = sum(s["gp"] for s in stints)
        print(f"  {'─' * 52}")
        print(f"  Total NHLe pts    : {total_nhle:.3f} over {total_gp:.1f} GP")
    print(f"  NHL pts / 82      : {pts82:.1f}")

    for s in wjc_stints:
        t = s["league_key"]
        print(f"  {t.upper():<7} {s['pts']:>4.0f}pts/{s['gp']:>2.0f}gp → {wjc[t]:.1f} NHLe pts/82 → "
              f"{wjc_log_odds(NHLER_WJC, {t: wjc[t]}):+.2f} NHLer / "
              f"{wjc_log_odds(STAR_WJC, {t: wjc[t]}):+.2f} star log-odds")

    print(f"  {'─' * 52}")
    print()
    print(f"  {render_bar(pn, ps)}")
    print(f"  ★★ Star (top 15% GAR) : {ps:.1%}")
    print(f"  ██ NHL player (200 GP+): {pn:.1%}  (includes star %)")
    print(f"  ░░ Bust (<200 GP)      : {1 - pn:.1%}")
    print()
    print("  Star ≈ David Krejci, Sean Monahan, Kevin Fiala, William Karlsson, Clayton Keller")
    print("  " + "═" * 52)
    print()


def print_leagues():
    print("\n  League              NHLe Factor")
    print("  " + "-" * 34)
    for k in sorted(LEAGUE_FACTORS):
        if k not in TOURNAMENTS:
            print(f"  {k:<20} {LEAGUE_FACTORS[k]:.4f}")
    print()


def ask(prompt, default=None):
    suffix = f" [Enter={default}]" if default is not None else ""
    val = input(f"    {prompt}{suffix}: ").strip()
    return str(default) if (val == "" and default is not None) else val


def collect_stints(label, kind, optional=False):
    stints = []
    print(f"\n  {label}")
    print(f"  {'─' * 40}")
    stint_num = 1
    while True:
        prefix = f"Stint {stint_num}" if stint_num > 1 else "League"
        raw = ask(f"{prefix} (or 'done'/'leagues')",
                  default="done" if optional else None)
        if raw.lower() in ("done", ""):
            break
        if raw.lower() == "leagues":
            print_leagues()
            continue
        try:
            league_key, factor = parse_league(raw)
        except ValueError as e:
            print(f"    ! {e}"); continue
        try:
            pts = parse_num(ask("Points"))
            gp  = parse_num(ask("Games played"))
        except ValueError:
            print("    ! Invalid number."); continue
        if gp <= 0:
            print("    ! GP must be > 0."); continue
        stints.append({"kind": kind, "pts": pts, "gp": gp,
                       "league_key": league_key, "factor": factor})
        print(f"    → {league_key.upper()}: {pts}pts/{gp}gp "
              f"({pts / gp:.3f} PPG) × {factor:.4f} NHLe")
        if ask("Add another stint?", default="n").lower() not in ("y", "yes"):
            break
        stint_num += 1
    return stints


def collect_wjc():
    """Each World Juniors this model uses: points and games, or skip."""
    stints = []
    for key in sorted(TOURNAMENTS):
        print(f"\n  {key.upper()}  (optional)")
        print(f"  {'─' * 40}")
        raw = ask("Points (or Enter to skip)", default="skip")
        if raw.lower() in ("skip", ""):
            continue
        try:
            pts, gp = parse_num(raw), parse_num(ask("Games played"))
        except ValueError:
            print(f"    ! Invalid number, skipping {key.upper()}."); continue
        if gp <= 0:
            print(f"    ! GP must be > 0, skipping {key.upper()}."); continue
        stints.append({"kind": key, "pts": pts, "gp": gp,
                       "league_key": key, "factor": LEAGUE_FACTORS[key]})
    return stints


def ask_known_outcomes():
    print("\n  KNOWN OUTCOMES  (if already achieved, outputs 100%)")
    print(f"  {'─' * 40}")
    known_nhler = ask("Has player already reached 200 NHL GP?", default="n").lower() in ("y", "yes")
    known_star = ask("Has player already hit star-level GAR (top 15%)?", default="n").lower() in ("y", "yes")
    return known_nhler, known_star


def main():
    # Bars and box-drawing characters crash cp1252 when output is redirected
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    args = sys.argv[1:]

    if len(args) == 2 and args[0] == "--pts82":
        try:
            pts82 = parse_num(args[1])
        except ValueError as e:
            sys.exit(f"  ! --pts82: {e}")
        show_result(pts82)
        return

    print("\n  NHLe Forward D+1 Model  (age ~19)")
    print("  " + "=" * 52)
    print("  Type 'leagues' at any league prompt to list all options.")

    known_nhler, known_star = ask_known_outcomes() if KNOWN_OUTCOMES else (False, False)

    reg = collect_stints("REGULAR SEASON  (required — add all splits)", "reg")
    if not reg:
        print("\n  ! No regular season data. Exiting."); sys.exit(1)
    po = collect_stints("PLAYOFFS  (optional — 'done' to skip)", "po", optional=True)
    wjc = collect_wjc()

    stints = reg + po
    show_result(compute_pts82(stints), stints, wjc, known_nhler, known_star)


if __name__ == "__main__":
    try:
        main()
    except (KeyboardInterrupt, EOFError):
        print("\n  Cancelled.")
        sys.exit(130)
